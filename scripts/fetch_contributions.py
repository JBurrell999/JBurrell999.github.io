#!/usr/bin/env python3
"""Fetch the last year of GitHub contributions and write assets/contributions.js.

Runs in the deploy workflow (with the workflow's GITHUB_TOKEN) and locally:

    GITHUB_TOKEN=$(gh auth token) python3 scripts/fetch_contributions.py

If the request fails, the existing file is left untouched so the site still
builds with the last good snapshot.
"""

import json
import os
import sys
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

LOGIN = os.environ.get("GH_LOGIN", "JBurrell999")
OUT = Path(__file__).resolve().parent.parent / "assets" / "contributions.js"
LEVELS = {
    "NONE": 0,
    "FIRST_QUARTILE": 1,
    "SECOND_QUARTILE": 2,
    "THIRD_QUARTILE": 3,
    "FOURTH_QUARTILE": 4,
}
QUERY = """
query($login: String!) {
  user(login: $login) {
    contributionsCollection {
      contributionCalendar {
        totalContributions
        weeks { contributionDays { date contributionCount contributionLevel } }
      }
    }
  }
}
"""


def main() -> int:
    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if not token:
        print("No GITHUB_TOKEN/GH_TOKEN set; keeping existing snapshot.")
        return 0

    body = json.dumps({"query": QUERY, "variables": {"login": LOGIN}}).encode()
    req = urllib.request.Request(
        "https://api.github.com/graphql",
        data=body,
        headers={
            "Authorization": f"bearer {token}",
            "Content-Type": "application/json",
            "User-Agent": "personal-site-contributions",
        },
    )
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            payload = json.load(resp)
        cal = payload["data"]["user"]["contributionsCollection"]["contributionCalendar"]
    except Exception as exc:  # network, auth, or schema problems
        print(f"Could not fetch contributions ({exc}); keeping existing snapshot.")
        return 0

    weeks = [
        [[d["date"], d["contributionCount"], LEVELS.get(d["contributionLevel"], 0)]
         for d in w["contributionDays"]]
        for w in cal["weeks"]
    ]
    data = {
        "login": LOGIN,
        "total": cal["totalContributions"],
        "updated": datetime.now(timezone.utc).strftime("%Y-%m-%d"),
        "weeks": weeks,
    }
    OUT.write_text(
        "// Generated by scripts/fetch_contributions.py, do not edit by hand.\n"
        f"window.CONTRIBUTIONS = {json.dumps(data, separators=(',', ':'))};\n"
    )
    print(f"Wrote {OUT.relative_to(Path.cwd()) if OUT.is_relative_to(Path.cwd()) else OUT}: "
          f"{data['total']} contributions over {len(weeks)} weeks")
    return 0


if __name__ == "__main__":
    sys.exit(main())
